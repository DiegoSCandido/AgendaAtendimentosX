/* Agendamentos e evoluções são gerados a partir da data atual para que o
   protótipo sempre abra com a semana preenchida. */
const at = (dias: number, hora: number, minuto = 0) => {
  const d = new Date();
  d.setDate(d.getDate() + dias);
  d.setHours(hora, minuto, 0, 0);
  return d.toISOString();
};

